async function publishAllBlogs() {
  console.log(`[1/3] Authenticating as Admin (${email})...`);
  const { data: authData, error: authErr } = await client.auth.signInWithPassword({
    email,
    password
  });

  if (authErr || !authData?.session) {
    console.error('❌ Authentication failed:', authErr?.message);
    return;
  }

  console.log(`✅ Authentication SUCCESS! User ID: ${authData.user.id}, Email: ${authData.user.email}`);

  console.log('\n[2/3] Publishing 3 Luxury Blog Posts to Supabase "public.blogs"...');
  
  for (const blog of blogsToPublish) {
    // Check if slug exists
    const { data: existing } = await client
      .from('blogs')
      .select('id, slug')
      .eq('slug', blog.slug)
      .maybeSingle();

    if (existing) {
      console.log(`Updating existing blog: ${blog.slug} (ID: ${existing.id})...`);
      const { data: updated, error: updErr } = await client
        .from('blogs')
        .update({
          ...blog,
          updated_at: new Date().toISOString()
        })
        .eq('id', existing.id)
        .select();

      if (updErr) {
        console.error(`❌ Error updating ${blog.slug}:`, updErr.message);
      } else {
        console.log(`✅ UPDATED: "${blog.title_bn}" (slug: ${blog.slug})`);
      }
    } else {
      console.log(`Inserting new blog: ${blog.slug}...`);
      const { data: inserted, error: insErr } = await client
        .from('blogs')
        .insert([{
          ...blog,
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString()
        }])
        .select();

      if (insErr) {
        console.error(`❌ Error inserting ${blog.slug}:`, insErr.message);
      } else {
        console.log(`✅ PUBLISHED: "${blog.title_bn}" (slug: ${blog.slug})`);
      }
    }
  }

  console.log('\n[3/3] Fetching all live blogs from Supabase to verify...');
  const { data: allBlogs, error: listErr } = await client
    .from('blogs')
    .select('id, title_bn, slug, category, read_time, published, created_at')
    .order('created_at', { ascending: false });

  if (listErr) {
    console.error('Error listing blogs:', listErr.message);
  } else {
    console.log(`\n🎉 TOTAL LIVE BLOGS IN GLAMOUR'S TOUCH: ${allBlogs.length}`);
    console.table(allBlogs);
  }
}

